class SweepAxisKind(Enum):
    """The parameter a sweep axis walks."""

    FREQUENCY = "frequency_hz"
    DRIVE_LEVEL = "drive_level"
    TEMPERATURE_SETPOINT = "temperature_setpoint_k"
    ORIENTATION = "orientation_deg"


class SweepStrategy(Enum):
    """How the sweep points are generated and traversed."""

    LINEAR = "LINEAR"
    LOGARITHMIC = "LOGARITHMIC"
    SPARSE = "SPARSE"
    RANDOMIZED = "RANDOMIZED"
    ADAPTIVE = "ADAPTIVE"


class SweepMode(Enum):
    """The four sweep execution modes, kept strictly distinct.

    ``REAL`` is never executed here (no apparatus); ``SYNTHETIC`` drives the
    runner's seeded deterministic simulator; ``REPLAY`` re-emits recorded
    frames; ``FAULT_INJECTION`` injects a deterministic fault. Each maps onto
    the corresponding :class:`r15.protocol_runner.ExecutionMode`."""

    REAL = "REAL"
    SYNTHETIC = "SYNTHETIC"
    REPLAY = "REPLAY"
    FAULT_INJECTION = "FAULT_INJECTION"

    @property
    def execution_mode(self) -> PR.ExecutionMode:
        return PR.ExecutionMode[self.name]


class PointStatus(Enum):
    """The outcome of a single planned sweep point. Every planned point ends
    in exactly one of these -- none is ever dropped."""

    COLLECTED = "COLLECTED"
    SETTLING_NOT_REACHED = "SETTLING_NOT_REACHED"
    CLIPPED_INVALID = "CLIPPED_INVALID"
    SAFETY_ABORTED = "SAFETY_ABORTED"
    PREREGISTERED_NOT_RUN = "PREREGISTERED_NOT_RUN"


#: The point statuses whose response is a usable, valid observation.
VALID_STATUSES = frozenset({PointStatus.COLLECTED})


# =======================================================================
# Safety bounds and sweep axes
# =======================================================================

@dataclass(frozen=True)
class SafetyBounds:
    """An inclusive [lo, hi] band a swept parameter may not leave.

    A point whose value falls outside the band is refused -- the controller
    does not drive an out-of-bounds setting, it records the point as
    ``SAFETY_ABORTED``. Safety is checked before any acquisition."""

    lo: float
    hi: float

    def __post_init__(self) -> None:
        if not (math.isfinite(self.lo) and math.isfinite(self.hi)):
            raise SweepError("safety bounds must be finite")
        if self.hi < self.lo:
            raise SweepError("safety bounds must satisfy lo <= hi")

    def contains(self, value: float) -> bool:
        return self.lo <= float(value) <= self.hi


@dataclass(frozen=True)
class SweepAxis:
    """One axis of a sweep: a kind, its grid of values, a settling time and
    a safety band.

    ``settle_time_s`` is the dwell a point on this axis needs before its
    reading is trustworthy; a controller dwell shorter than this marks the
    point ``SETTLING_NOT_REACHED``. ``safety`` bounds the parameter; a value
    outside it is refused. The values are a frozen tuple so an axis is
    immutable and hashable."""

    kind: SweepAxisKind
    values: tuple
    unit: str = ""
    settle_time_s: float = 0.0
    safety: SafetyBounds | None = None

    def __post_init__(self) -> None:
        if not isinstance(self.kind, SweepAxisKind):
            raise SweepError("axis kind must be a SweepAxisKind")
        vals = tuple(float(v) for v in self.values)
        if len(vals) < 1:
            raise SweepError("a sweep axis needs at least one value")
        if not all(math.isfinite(v) for v in vals):
            raise SweepError("axis values must be finite")
        if self.settle_time_s < 0.0:
            raise SweepError("settle_time_s must be non-negative")
        object.__setattr__(self, "values", vals)

    def within_safety(self, value: float) -> bool:
        return self.safety is None or self.safety.contains(value)

    def to_spec(self) -> dict:
        spec = {
            "kind": self.kind.value,
            "values": [float(v) for v in self.values],
            "unit": self.unit,
            "settle_time_s": float(self.settle_time_s),
        }
        if self.safety is not None:
            spec["safety"] = {"lo": float(self.safety.lo),
                              "hi": float(self.safety.hi)}
        return spec


# --- axis generators ------------------------------------------------------

def linear_axis(kind: SweepAxisKind, start: float, stop: float, n: int,
                *, unit: str = "", settle_time_s: float = 0.0,
                safety: SafetyBounds | None = None) -> SweepAxis:
    """A linearly spaced axis of ``n`` points on ``[start, stop]``."""
    if int(n) < 1:
        raise SweepError("a linear axis needs at least one point")
    vals = np.linspace(float(start), float(stop), int(n))
    return SweepAxis(kind, tuple(float(v) for v in vals), unit=unit,
                     settle_time_s=settle_time_s, safety=safety)


def log_axis(kind: SweepAxisKind, start: float, stop: float, n: int,
             *, unit: str = "", settle_time_s: float = 0.0,
             safety: SafetyBounds | None = None) -> SweepAxis:
    """A logarithmically spaced axis of ``n`` points on ``[start, stop]``.

    Both endpoints must be strictly positive -- a decade grid is undefined
    through zero -- so a non-positive endpoint is refused rather than folded
    into a NaN."""
    if int(n) < 1:
        raise SweepError("a log axis needs at least one point")
    if float(start) <= 0.0 or float(stop) <= 0.0:
        raise SweepError(
            "a logarithmic axis needs strictly positive endpoints")
    vals = np.logspace(math.log10(float(start)), math.log10(float(stop)),
                       int(n))
    return SweepAxis(kind, tuple(float(v) for v in vals), unit=unit,
                     settle_time_s=settle_time_s, safety=safety)


def sparse_axis(kind: SweepAxisKind, values, *, unit: str = "",
                settle_time_s: float = 0.0,
                safety: SafetyBounds | None = None) -> SweepAxis:
    """A sparse axis: an explicit, arbitrary set of values (sorted, unique)."""
    uniq = sorted({float(v) for v in values})
    if not uniq:
        raise SweepError("a sparse axis needs at least one value")
    return SweepAxis(kind, tuple(uniq), unit=unit,
                     settle_time_s=settle_time_s, safety=safety)


# =======================================================================
# The adaptive-refinement policy (must be pre-declared in the sealed plan)
# =======================================================================

@dataclass(frozen=True)
class AdaptivePolicy:
    """A pre-declared adaptive-refinement policy.

    Adaptive refinement -- bisecting toward a feature such as a resonance --
    is legitimate only when it is declared *before* the sweep runs and sealed
    into the plan. A policy carries the axis it refines, how many refinement
    evaluations it may spend, the objective, and a convergence tolerance. The
    ``pre_declared`` flag is the honesty bit: refinement without it is
    post-hoc cherry-picking and is refused."""

    axis: SweepAxisKind
    max_refinements: int = 8
    objective: str = "MAXIMIZE_RESPONSE"
    tolerance: float = 0.0
    pre_declared: bool = True

    def __post_init__(self) -> None:
        if not isinstance(self.axis, SweepAxisKind):
            raise SweepError("adaptive axis must be a SweepAxisKind")
        if int(self.max_refinements) < 1:
            raise SweepError("max_refinements must be >= 1")
        if self.objective != "MAXIMIZE_RESPONSE":
            raise SweepError(
                f"unsupported adaptive objective {self.objective!r}; only "
                f"MAXIMIZE_RESPONSE is implemented")

    def to_spec(self) -> dict:
        return {
            "axis": self.axis.value,
            "max_refinements": int(self.max_refinements),
            "objective": self.objective,
            "tolerance": float(self.tolerance),
            "pre_declared": bool(self.pre_declared),
        }


# =======================================================================
# The sweep plan and its seal
# =======================================================================

@dataclass(frozen=True)
class SweepPlan:
    """A frozen plan for a parameter sweep.

    The points are the Cartesian product of the axes' values, taken in axis
    order. ``strategy`` documents how the grid was built and traversed;
    ``mode`` selects the execution mode; ``seed`` makes a synthetic sweep and
    a randomized traversal reproducible; ``dwell_s`` is the settling dwell
    spent at each point. ``adaptive`` is the pre-declared refinement policy
    (or ``None``). ``lanes`` names the measurement lanes the sweep drives, for
    the record. A plan is sealed with :func:`freeze` before it runs."""

    plan_id: str
    axes: tuple
    strategy: SweepStrategy
    mode: SweepMode
    seed: int
    dwell_s: float = 1.0
    adaptive: AdaptivePolicy | None = None
    lanes: tuple = ()

    def __post_init__(self) -> None:
        if not self.axes:
            raise SweepError("a sweep plan needs at least one axis")
        if not all(isinstance(a, SweepAxis) for a in self.axes):
            raise SweepError("every axis must be a SweepAxis")
        if not isinstance(self.strategy, SweepStrategy):
            raise SweepError("strategy must be a SweepStrategy")
        if not isinstance(self.mode, SweepMode):
            raise SweepError("mode must be a SweepMode")
        if self.dwell_s < 0.0:
            raise SweepError("dwell_s must be non-negative")
        if self.strategy is SweepStrategy.ADAPTIVE and self.adaptive is None:
            raise SweepError(
                "an ADAPTIVE strategy needs a pre-declared AdaptivePolicy; "
                "adaptive refinement must be declared before the sweep runs")
        if self.adaptive is not None:
            if len(self.axes) != 1:
                raise SweepError(
                    "adaptive refinement is defined over a single continuous "
                    "axis; provide exactly one axis when adaptive is set")
            if self.axes[0].kind is not self.adaptive.axis:
                raise SweepError(
                    "the adaptive policy axis must match the plan's axis")

    @property
    def axis_kinds(self) -> tuple:
        return tuple(a.kind for a in self.axes)

    def base_points(self) -> tuple:
        """The Cartesian product of the axes, as ordered :class:`SweepPoint`s.

        Product order is axis order (the first axis varies slowest), then the
        traversal is reordered by :meth:`ordered_points`."""
        grids = [a.values for a in self.axes]
        kinds = [a.kind for a in self.axes]
        points: list[SweepPoint] = []
        idx = 0
        for combo in _cartesian(grids):
            params = {kinds[i].value: float(combo[i])
                      for i in range(len(kinds))}
            points.append(SweepPoint(index=idx, params=params, phase="base"))
            idx += 1
        return tuple(points)

    def ordered_points(self) -> tuple:
        """The base points in traversal order.

        For every strategy but ``RANDOMIZED`` the order is the natural
        product order. ``RANDOMIZED`` permutes the indices with the P08
        randomization engine under the plan seed, so the order is reproducible
        and pre-committed -- it cannot be chosen after seeing the data."""
        pts = self.base_points()
        if self.strategy is SweepStrategy.RANDOMIZED:
            order = RND.randomize(tuple(range(len(pts))),
                                  RND.derive_seed(self.seed, "sweep_order"))
            return tuple(pts[i] for i in order)
        return pts

    def spec(self) -> dict:
        """A canonical, JSON-friendly spec of the plan (for the seal)."""
        return {
            "plan_id": self.plan_id,
            "axes": [a.to_spec() for a in self.axes],
            "strategy": self.strategy.value,
            "mode": self.mode.value,
            "seed": int(self.seed),
            "dwell_s": float(self.dwell_s),
            "adaptive": self.adaptive.to_spec() if self.adaptive else None,
            "lanes": list(self.lanes),
            "controller_version": CONTROLLER_VERSION,
        }

    def plan_hash(self) -> str:
        """A stable content hash of the plan spec (reuses R13 serialize)."""
        return r13_serialize.content_hash(self.spec())


@dataclass(frozen=True)
class SealedSweepPlan:
    """A sweep plan sealed before it runs.

    Carries the plan, a seal (the plan hash at freeze time) and the epoch it
    was sealed at. :meth:`verify` recomputes the hash and detects an edit
    after the seal -- a plan changed after freezing may not run under the old
    seal."""

    plan: SweepPlan
    seal: str
    sealed_epoch: int

    def verify(self) -> bool:
        return self.plan.plan_hash() == self.seal


def freeze(plan: SweepPlan, *, epoch: int) -> SealedSweepPlan:
    """Seal a sweep plan by committing its content hash at ``epoch``."""
    if not isinstance(plan, SweepPlan):
        raise SweepError("freeze expects a SweepPlan")
    return SealedSweepPlan(plan=plan, seal=plan.plan_hash(),
                           sealed_epoch=int(epoch))


def _cartesian(grids):
    """Yield the Cartesian product of a list of value tuples, first slowest."""
    if not grids:
        yield ()
        return
    head, *rest = grids
    for v in head:
        for tail in _cartesian(rest):
            yield (v,) + tail


