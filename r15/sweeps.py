CONTROLLER_VERSION = "r15.sweeps/1.0"


class SweepError(RuntimeError):
    """Raised on any sweep-controller refusal or misuse.

    Covers the structural guards (an empty axis, an out-of-order safety
    band, an adaptive plan over more than one axis) and the load-bearing
    refusals (a dropped/omitted point, a post-hoc adaptive refinement that
    was not pre-declared in the sealed plan, a synthetic response read as a
    measurement).
    """


# =======================================================================
# Enumerations: the axis kinds, strategies, modes and point statuses
