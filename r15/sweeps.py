@dataclass(frozen=True)
class SweepPoint:
    """One planned point in the sweep: an index, its parameter dict, and
    whether it is a ``base`` grid point or an adaptive ``refine`` point."""

    index: int
    params: dict
    phase: str = "base"

    def value_on(self, kind: SweepAxisKind) -> float:
        return float(self.params[kind.value])


@dataclass(frozen=True)
class ResponseSample:
    """A deterministic synthetic response at one sweep point.

    ``value`` is the modelled response; ``clipped`` marks a drive that
    saturated the response (an invalid step); ``claim_class`` is a
    ``SYNTHETIC_OBSERVATION`` and never a measurement class."""

    value: float
    clipped: bool
    claim_class: str = POINT_CLAIM_CLASS.value

    def as_dict(self) -> dict:
        return {"value": float(self.value), "clipped": bool(self.clipped),
                "claim_class": self.claim_class,
                "measured_here": MEASURED_HERE}


@dataclass(frozen=True)
class SweepPointResult:
    """The record of one attempted sweep point -- always kept.

    Carries the point, the run id, the point status, whether it settled and
    clipped, the synthetic response (``None`` for a safety-aborted or a real
    point), and the ``ExperimentRun`` record the runner produced (``None``
    when the point was not driven). No point result is ever discarded."""

    point_index: int
    run_id: str
    phase: str
    params: dict
    status: PointStatus
    settled: bool
    clipped: bool
    response: ResponseSample | None
    experiment_run: dict | None

    @property
    def is_valid(self) -> bool:
        return self.status in VALID_STATUSES

    def to_record(self) -> dict:
        return {
            "point_index": int(self.point_index),
            "run_id": self.run_id,
            "phase": self.phase,
            "params": dict(self.params),
            "status": self.status.value,
            "settled": bool(self.settled),
            "clipped": bool(self.clipped),
            "response": self.response.as_dict() if self.response else None,
            "experiment_run": self.experiment_run,
        }


@dataclass(frozen=True)
class SweepResult:
    """The full record of a sweep: every point, in traversal order.

    ``feature_estimate`` is the (parameter value, response) of the strongest
    valid point along the adaptive axis, or ``None`` when nothing valid was
    collected. ``n_planned`` is the number of base points; ``points`` also
    includes any adaptive refinement points. No planned point is missing --
    :func:`refuse_dropped_points` is asserted before the result is returned."""

    plan_id: str
    seal: str
    mode: str
    strategy: str
    n_planned: int
    points: tuple
    feature_estimate: dict | None

    def status_counts(self) -> dict:
        counts: dict = {}
        for r in self.points:
            counts[r.status.value] = counts.get(r.status.value, 0) + 1
        return counts

    def valid_points(self) -> tuple:
        return tuple(r for r in self.points if r.is_valid)

    def run_ids(self) -> tuple:
        return tuple(r.run_id for r in self.points)

    def base_results(self) -> tuple:
        return tuple(r for r in self.points if r.phase == "base")

    def to_record(self) -> dict:
        return {
            "plan_id": self.plan_id,
            "seal": self.seal,
            "mode": self.mode,
            "strategy": self.strategy,
            "controller_version": CONTROLLER_VERSION,
            "n_planned": int(self.n_planned),
            "n_recorded": len(self.points),
            "status_counts": self.status_counts(),
            "feature_estimate": self.feature_estimate,
            "points": [r.to_record() for r in self.points],
            "claim_class": POINT_CLAIM_CLASS.value,
            "measured_here": MEASURED_HERE,
            "physical_validation": PHYSICAL_VALIDATION,
        }


# =======================================================================
# The synthetic response model (deterministic; plants a feature)
# =======================================================================

@dataclass(frozen=True)
class PlantedFeature:
    """A feature planted in the synthetic response: a Lorentzian resonance in
    frequency, centred at ``center_hz`` with half-width ``width_hz`` and peak
    ``height``.

    A synthetic feature, not a specimen resonance. The controller's adaptive
    refinement recovers this planted centre; recovering a number this module
    planted is never a measurement of a real resonance."""

    center_hz: float
    width_hz: float
    height: float = 1.0

    def __post_init__(self) -> None:
        if self.width_hz <= 0.0 or not math.isfinite(self.width_hz):
            raise SweepError("a planted feature needs a positive width")
        if self.center_hz <= 0.0:
            raise SweepError("a planted feature needs a positive centre")

    def lorentzian(self, frequency_hz: float) -> float:
        d = (float(frequency_hz) - self.center_hz) / self.width_hz
        return float(self.height) / (1.0 + d * d)


@dataclass(frozen=True)
class SyntheticResponseModel:
    """A deterministic model of a swept response with a planted feature.

    The response is the planted Lorentzian in frequency, scaled by the drive
    level and shifted by any temperature offset, plus a tiny seeded noise. A
    drive above ``drive_clip_level`` saturates the response: the sample is
    flagged ``clipped`` and pinned at ``clip_value`` -- a clipped step is
    invalid. Everything is a pure function of the parameters and the seed:
    the same point always yields the same response."""

    feature: PlantedFeature
    reference_temperature_k: float = 300.0
    temperature_coefficient: float = 0.0
    drive_clip_level: float = 5.0
    clip_value: float = 1.0e3
    noise: float = 1.0e-6
    baseline: float = 0.0

    def response(self, params: dict, seed: int) -> ResponseSample:
        freq = float(params.get(SweepAxisKind.FREQUENCY.value,
                                self.feature.center_hz))
        drive = float(params.get(SweepAxisKind.DRIVE_LEVEL.value, 1.0))
        temp = float(params.get(SweepAxisKind.TEMPERATURE_SETPOINT.value,
                                self.reference_temperature_k))
        center = self.feature.center_hz * (
            1.0 + self.temperature_coefficient
            * (temp - self.reference_temperature_k))
        d = (freq - center) / self.feature.width_hz
        peak = float(self.feature.height) / (1.0 + d * d)
        amp = drive * peak + self.baseline
        clipped = drive > self.drive_clip_level or amp > self.clip_value
        # Deterministic per-point noise, a pure function of (params, seed).
        digest = r13_serialize.content_hash(
            {"params": {k: float(v) for k, v in sorted(params.items())},
             "seed": int(seed)})
        rng = np.random.default_rng(int(digest[:16], 16))
        value = amp + float(self.noise) * float(rng.standard_normal())
        if clipped:
            value = float(self.clip_value)
        return ResponseSample(value=value, clipped=bool(clipped))


# =======================================================================
# The controller
# =======================================================================

class SweepController:
    """The automated sweep controller.

    Drives a sealed sweep plan against a frozen protocol, one point at a
    time, collecting an :class:`~r15.protocol_runner.ExperimentRun` per point
    and (for a synthetic sweep) a deterministic response sample. Enforces the
    settling, safety-bound and clipping policies, records every planned point
    whatever its outcome, refines adaptively only when the plan pre-declared
    it, and supports checkpoint/resume without duplicating evidence."""

    def __init__(self, sealed_plan: SealedSweepPlan,
                 sealed_protocol: P.SealedProtocol,
                 base_config: PR.RunConfig,
                 response_model: SyntheticResponseModel | None = None) -> None:
        if not isinstance(sealed_plan, SealedSweepPlan):
            raise SweepError("sealed_plan must be a SealedSweepPlan")
        if not sealed_plan.verify():
            raise SweepError(
                "refused: the sweep plan seal is broken; a plan edited after "
                "freezing may not run under the old seal")
        if not isinstance(base_config, PR.RunConfig):
            raise SweepError("base_config must be a RunConfig")
        self.sealed_plan = sealed_plan
        self.plan = sealed_plan.plan
        self.sealed_protocol = sealed_protocol
        self.base_config = base_config
        self.model = response_model

    # --- settling ------------------------------------------------------

    def _settle_required(self) -> float:
        """The dwell a point needs: the longest axis settling time."""
        return max((a.settle_time_s for a in self.plan.axes), default=0.0)

    def _settled(self) -> bool:
        return self.plan.dwell_s >= self._settle_required()

    # --- safety --------------------------------------------------------

    def _within_safety(self, point: SweepPoint) -> bool:
        for axis in self.plan.axes:
            if axis.kind.value in point.params:
                if not axis.within_safety(point.params[axis.kind.value]):
                    return False
        return True

    # --- one point -----------------------------------------------------

    def _run_id(self, point: SweepPoint) -> str:
        tag = "R" if point.phase == "refine" else "P"
        return f"{self.plan.plan_id}-{tag}{point.index:04d}"

    def _drive_point(self, point: SweepPoint, epoch: int,
                     mode: PR.ExecutionMode) -> dict:
        """Drive the frozen protocol at one point, returning the run record."""
        cfg = replace(
            self.base_config, mode=mode,
            seed=int(self.base_config.seed) + int(point.index),
            environment={**dict(self.base_config.environment), **point.params,
                         "sweep_plan_id": self.plan.plan_id,
                         "sweep_point_index": int(point.index)})
        run = PR.execute(self.sealed_protocol, cfg,
                         run_id=self._run_id(point), epoch=int(epoch))
        return run.to_record()

    def _run_point(self, point: SweepPoint, epoch: int) -> SweepPointResult:
        """Run one point under the plan's mode, recording it whatever happens."""
        run_id = self._run_id(point)

        # A real sweep runs nothing: the point is preregistered, not run.
        if self.plan.mode is SweepMode.REAL:
            run_rec = self._drive_point(point, epoch, PR.ExecutionMode.REAL)
            return SweepPointResult(
                point_index=point.index, run_id=run_id, phase=point.phase,
                params=dict(point.params),
                status=PointStatus.PREREGISTERED_NOT_RUN,
                settled=False, clipped=False, response=None,
                experiment_run=run_rec)

        # Safety: an out-of-bounds setting is never driven.
        if not self._within_safety(point):
            return SweepPointResult(
                point_index=point.index, run_id=run_id, phase=point.phase,
                params=dict(point.params), status=PointStatus.SAFETY_ABORTED,
                settled=False, clipped=False, response=None,
                experiment_run=None)

        # Drive the protocol (produces the ExperimentRun) and model the
        # response.
        run_rec = self._drive_point(point, epoch, self.plan.mode.execution_mode)
        sample = None
        if self.model is not None:
            sample = self.model.response(point.params,
                                         int(self.base_config.seed))
        settled = self._settled()
        clipped = bool(sample.clipped) if sample is not None else False

        if clipped:
            status = PointStatus.CLIPPED_INVALID
        elif not settled:
            status = PointStatus.SETTLING_NOT_REACHED
        else:
            status = PointStatus.COLLECTED
        return SweepPointResult(
            point_index=point.index, run_id=run_id, phase=point.phase,
            params=dict(point.params), status=status, settled=settled,
            clipped=clipped, response=sample, experiment_run=run_rec)

    # --- adaptive refinement (only if pre-declared) --------------------

    def _adaptive_refine(self, base_results, epoch: int,
                         start_index: int) -> list:
        """Bisect toward the strongest valid base point (ternary search).

        Runs ONLY when the sealed plan pre-declared an :class:`AdaptivePolicy`.
        Uses the valid base points along the adaptive axis to bracket the
        maximum, then narrows the bracket by ternary search, evaluating a new
        refinement point per step. Converges to the planted feature for a
        unimodal response."""
        policy = self.plan.adaptive
        refuse_adaptive_as_cherrypicking(policy)
        axis = policy.axis
        valid = [r for r in base_results if r.is_valid and r.response
                 is not None]
        if len(valid) < 3:
            return []  # not enough bracket to refine
        valid.sort(key=lambda r: r.params[axis.value])
        vals = [r.params[axis.value] for r in valid]
        resp = [r.response.value for r in valid]
        peak = int(np.argmax(resp))
        lo_i = max(0, peak - 1)
        hi_i = min(len(vals) - 1, peak + 1)
        lo, hi = vals[lo_i], vals[hi_i]

        refined: list = []
        idx = int(start_index)
        for _ in range(int(policy.max_refinements)):
            if hi - lo <= policy.tolerance:
                break
            m1 = lo + (hi - lo) / 3.0
            m2 = hi - (hi - lo) / 3.0
            r1 = self._evaluate_refine_point(axis, m1, valid[peak], idx, epoch)
            idx += 1
            r2 = self._evaluate_refine_point(axis, m2, valid[peak], idx, epoch)
            idx += 1
            refined.extend([r1, r2])
            v1 = r1.response.value if r1.response else -math.inf
            v2 = r2.response.value if r2.response else -math.inf
            if v1 < v2:
                lo = m1
            else:
                hi = m2
        return refined

    def _evaluate_refine_point(self, axis: SweepAxisKind, value: float,
                               template: SweepPointResult, index: int,
                               epoch: int) -> SweepPointResult:
        params = dict(template.params)
        params[axis.value] = float(value)
        point = SweepPoint(index=index, params=params, phase="refine")
        return self._run_point(point, epoch)

    # --- the run -------------------------------------------------------

    def run(self, *, epoch: int, resume_from: SweepResult | None = None,
            max_points: int | None = None) -> SweepResult:
        """Run the sealed sweep, recording every planned point.

        ``resume_from`` carries the results of an interrupted sweep; already
        recorded base points are reused unchanged (no re-drive, no duplicate
        run id) and only the remaining points are driven. ``max_points`` stops
        the base traversal early (a checkpoint) -- the returned partial result
        can be handed back as ``resume_from``. Adaptive refinement runs only
        after the full base grid is complete and only if pre-declared."""
        if not self.sealed_plan.verify():
            raise SweepError(
                "refused: the sweep plan seal is broken; cannot run an edited "
                "plan under the old seal")

        ordered = self.plan.ordered_points()
        done: dict = {}
        if resume_from is not None:
            for r in resume_from.base_results():
                done[r.point_index] = r

        results: list = []
        driven = 0
        for point in ordered:
            if point.index in done:
                results.append(done[point.index])
                continue
            if max_points is not None and driven >= int(max_points):
                # Checkpoint: stop driving new points here.
                break
            results.append(self._run_point(point, epoch))
            driven += 1

        base_recorded = {r.point_index for r in results}
        planned = len(ordered)
        base_complete = len(base_recorded) == planned

        # Adaptive refinement only over a complete base grid, and only if the
        # plan pre-declared it. Never on a real sweep (nothing was measured).
        refined: list = []
        if (base_complete and self.plan.adaptive is not None
                and self.plan.mode is not SweepMode.REAL):
            refined = self._adaptive_refine(results, epoch,
                                            start_index=planned)

        all_results = results + refined

        # A complete run must contain every planned point -- no silent drops.
        if base_complete:
            refuse_dropped_points(range(planned),
                                  [r.point_index for r in results])

        feature = _feature_estimate(all_results, self.plan)
        return SweepResult(
            plan_id=self.plan.plan_id, seal=self.sealed_plan.seal,
            mode=self.plan.mode.value, strategy=self.plan.strategy.value,
            n_planned=planned, points=tuple(all_results),
            feature_estimate=feature)


def _feature_estimate(results, plan: SweepPlan) -> dict | None:
    """The (value, response) of the strongest valid point along the adaptive
    axis, or ``None`` when nothing valid was collected."""
    axis = plan.adaptive.axis if plan.adaptive else plan.axes[0].kind
    valid = [r for r in results if r.is_valid and r.response is not None]
    if not valid:
        return None
    best = max(valid, key=lambda r: r.response.value)
    return {
        "axis": axis.value,
        "value": float(best.params.get(axis.value, math.nan)),
        "response": float(best.response.value),
        "run_id": best.run_id,
        "phase": best.phase,
    }


