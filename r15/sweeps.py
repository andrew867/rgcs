def refuse_adaptive_as_cherrypicking(policy) -> None:
    """Refuse adaptive refinement that was not pre-declared in the sealed
    plan. Raises.

    Bisecting toward a feature *after* the sweep has run and the data is in
    hand is cherry-picking: the operator would be choosing which points to
    add having already seen which region flatters the answer. Legitimate
    adaptive refinement is declared in the plan and sealed before the run, so
    its policy carries ``pre_declared=True``. A missing policy, or one whose
    ``pre_declared`` flag is not set, is refused here."""
    if policy is None:
        raise SweepError(
            "refused: adaptive refinement requested with no pre-declared "
            "AdaptivePolicy. Bisecting toward a feature after the data is in "
            "hand is cherry-picking. Declare the refinement in the plan and "
            "seal it BEFORE the sweep runs.")
    if not getattr(policy, "pre_declared", False):
        raise SweepError(
            "refused: the adaptive policy is not marked pre_declared. Adaptive "
            "refinement must be committed in the sealed plan before the run; a "
            "post-hoc refinement chosen after seeing the data is "
            "cherry-picking, not refinement.")


def refuse_dropped_points(expected_indices, recorded_indices) -> None:
    """Refuse a sweep record that is missing a planned point. Raises.

    Every planned point must appear in the record, whatever became of it: a
    safety-aborted, a settling-not-reached and a clipped-invalid point are
    all *kept*, because silently dropping the points that misbehaved is how a
    sweep is made to look cleaner than it was. A missing planned index is
    refused."""
    expected = set(int(i) for i in expected_indices)
    recorded = set(int(i) for i in recorded_indices)
    missing = sorted(expected - recorded)
    if missing:
        raise SweepError(
            f"refused: {len(missing)} planned sweep point(s) are missing from "
            f"the record: {missing}. Every planned point must be recorded -- "
            f"settling-not-reached, clipped and safety-aborted points are "
            f"kept, never dropped. A sweep that hides its bad points is not "
            f"honest.")


def refuse_synthetic_response_as_measurement(*_a, **_k) -> None:
    """Refuse a synthetic sweep response read as a physical measurement.

    Every response the controller collects is a ``SYNTHETIC_OBSERVATION`` --
    a number modelled from the swept parameters, reproducible from the seed,
    not transduced from a specimen. This delegates to the governance core's
    standing refusal."""
    C.refuse_synthetic_as_physical()


def refuse_feature_as_resonance(*_a, **_k) -> None:
    """Refuse a swept synthetic feature read as a physical resonance.

    The feature the adaptive refinement converges to is the Lorentzian this
    module PLANTED; there is no specimen and no measured resonance. Delegates
    to the governance core's noise/feature refusal."""
    C.refuse_noise_as_resonance()


