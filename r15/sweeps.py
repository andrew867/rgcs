"""P27 — the automated sweep controller: orchestrate a parameter sweep
across measurement lanes, driving a frozen protocol, honestly.

A single measurement point answers one question at one setting. A *sweep*
walks a parameter -- a drive frequency, a drive level, a temperature
setpoint, a specimen orientation -- across a grid (or a Cartesian product of
several), drives the frozen protocol at each point, and collects an
:class:`~r15.protocol_runner.ExperimentRun` per point. This module is that
controller, and like every other R15 module it is bounded by what the
environment can honestly produce.

**Reuse, not a new truth system.** The controller drives the P07 protocol
runner (:mod:`r15.protocol_runner`) at every point, so each point yields a
real ``ExperimentRun`` conforming to ``experiment_run.schema.json``; it
orders the sweep with the P08 randomization engine
(:mod:`r15.randomization`) so a randomized traversal is reproducible and
pre-committed; and it types every result through the governance core
(:mod:`r15.claims`). No parallel authority is invented.

**Five sweep strategies.** :class:`SweepStrategy` supports ``LINEAR``,
``LOGARITHMIC``, ``SPARSE``, ``RANDOMIZED`` and ``ADAPTIVE`` traversals. The
axis values are generated by :func:`linear_axis`, :func:`log_axis` or
:func:`sparse_axis`; ``RANDOMIZED`` permutes the traversal under a committed
seed (so the order is reproducible and tamper-evident, never chosen after
the data); ``ADAPTIVE`` refines toward a feature -- but only when the
refinement was **pre-declared** in the sealed plan.

**Four honest modes.** A ``SYNTHETIC`` sweep drives the runner's synthetic
simulator and is byte-identical under a seed. A ``REAL`` sweep runs nothing:
there is no bench, so every point is recorded ``PREREGISTERED_NOT_RUN`` with
no synthetic response. ``REPLAY`` and ``FAULT_INJECTION`` pass through to the
runner's corresponding modes. A synthetic response is never a measurement.

**No point is ever silently dropped.** Every planned point is recorded,
whatever happens to it: a point outside its axis's safety bounds is
``SAFETY_ABORTED`` (and never driven); a point whose dwell is shorter than
its settling requirement is ``SETTLING_NOT_REACHED``; a point whose drive
clips the response is ``CLIPPED_INVALID``. Each of those is kept in the
record, and :func:`refuse_dropped_points` refuses a record that is missing a
planned point. :func:`refuse_adaptive_as_cherrypicking` refuses adaptive
refinement that was not pre-declared in the sealed plan, because bisecting
toward a feature *after* seeing the data is cherry-picking, not refinement.

**Checkpoint and resume.** A partial :class:`SweepResult` can be handed back
to :meth:`SweepController.run` as ``resume_from``; already-recorded points
are carried through unchanged and only the remaining points are driven, so a
resumed sweep produces no duplicate evidence (no duplicate ``run_id``).

Nothing here is measured. The strongest class a synthetic sweep point
reaches is a ``SYNTHETIC_OBSERVATION``; a real sweep is
``PREREGISTERED_NOT_RUN``. ``measured_here = "nothing"`` and
``PHYSICAL_VALIDATION_NOT_CLAIMED``.
"""

